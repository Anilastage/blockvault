import { api, unwrap, getBlobError, saveBlob } from './api';
import type {
  AnalyticsOverview,
  BlockchainAnalytics,
  DocumentsAnalytics,
  VerificationsAnalytics,
} from '@/types';

export interface AnalyticsRange {
  from?: string;
  to?: string;
}

export const analyticsService = {
  async overview(range: AnalyticsRange = {}): Promise<AnalyticsOverview> {
    const res = await api.get('/analytics/overview', { params: range });
    return unwrap(res.data);
  },

  async documents(range: AnalyticsRange = {}): Promise<DocumentsAnalytics> {
    const res = await api.get('/analytics/documents', { params: range });
    return unwrap(res.data);
  },

  async verifications(range: AnalyticsRange = {}): Promise<VerificationsAnalytics> {
    const res = await api.get('/analytics/verifications', { params: range });
    return unwrap(res.data);
  },

  async blockchain(range: AnalyticsRange = {}): Promise<BlockchainAnalytics> {
    const res = await api.get('/analytics/blockchain', { params: range });
    return unwrap(res.data);
  },

  /** Downloads the real CSV report generated by the backend. */
  async exportCsv(): Promise<void> {
    try {
      const res = await api.get('/analytics/export', { responseType: 'blob' });
      saveBlob(res.data as Blob, `blockvault-report-${new Date().toISOString().slice(0, 10)}.csv`);
    } catch (err) {
      throw await getBlobError(err);
    }
  },
};
